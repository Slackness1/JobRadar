def tag_industries(job_title: str, description: str = '', max_tags: int = 2) -> list[str]:
    """给定 job_title + (optional) description,返回 0-max_tags 个 industry tag。

    Order-preserving:按 `_INDUSTRY_RULES` 表顺序匹配,先命中优先。
    """
    if not job_title and not description:
        return []
    text = f"{job_title} {description or ''}".lower()
    tags: list[str] = []
    for label, kws in _INDUSTRY_RULES:
        if any(kw in text for kw in kws):
            tags.append(label)
            if len(tags) >= max_tags:
                break
    return tags
